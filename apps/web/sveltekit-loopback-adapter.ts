import { readFile, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import bunAdapter from '@sveltejs/adapter-bun';
import type { Adapter } from '@sveltejs/kit';

/**
 * `@sveltejs/adapter-bun` derives every request's origin from the build-time `paths.origin`, or
 * else from `https://<Host>`. This server is plain HTTP on numeric loopback with a port chosen at
 * start, so neither is the origin the browser actually uses. The adapter hands its build-time
 * values to the server through one generated module; the wrapper keeps that module intact and puts
 * a module in front of it whose `origin` export is read from the `ORIGIN` variable `start.mjs`
 * sets to `http://127.0.0.1:<PORT>`. Request URLs, SvelteKit's CSRF self-origin and the RPC
 * origin policy then all see the listener's real origin, as they did with `svelte-adapter-bun`.
 */
export const RUNTIME_ORIGIN_VARIABLE = 'ORIGIN';

const HANDOFF_MODULE = 'adapter-bun.js';
const GENERATED_HANDOFF_MODULE = 'adapter-bun.generated.js';
const UNCONFIGURED_ORIGIN_EXPORT = 'export const origin = undefined;';
const ORIGIN_EXPORT_PREFIX = 'export const origin';

export const runtimeOriginHandoffSource = (generatedHandoffSource: string): string => {
  const originExports = generatedHandoffSource.split('\n').filter((line) => line.startsWith(ORIGIN_EXPORT_PREFIX));
  if (originExports.length !== 1 || originExports[0] !== UNCONFIGURED_ORIGIN_EXPORT) {
    throw new Error(
      `The Bun adapter hand-off module no longer exports exactly one unconfigured origin (found ${JSON.stringify(originExports)}). Review the adapter upgrade before binding the runtime origin.`,
    );
  }
  return [
    '// Generated by apps/web/sveltekit-loopback-adapter.ts: binds the request origin at server start.',
    `export * from './${GENERATED_HANDOFF_MODULE}';`,
    '',
    `const runtimeOrigin = process.env.${RUNTIME_ORIGIN_VARIABLE};`,
    'const isCanonicalHttpOrigin = (value) => {',
    '  try {',
    '    const url = new URL(value);',
    "    return (url.protocol === 'http:' || url.protocol === 'https:') && url.origin === value;",
    '  } catch {',
    '    return false;',
    '  }',
    '};',
    'if (runtimeOrigin === undefined || !isCanonicalHttpOrigin(runtimeOrigin)) {',
    `  throw new Error('${RUNTIME_ORIGIN_VARIABLE} must be the canonical origin of this listener; start the server through apps/web/start.mjs.');`,
    '}',
    '',
    'export const origin = runtimeOrigin;',
    '',
  ].join('\n');
};

export const bindRuntimeOrigin = async (outputDirectory: string): Promise<void> => {
  const handoffPath = path.join(outputDirectory, HANDOFF_MODULE);
  const overrideSource = runtimeOriginHandoffSource(await readFile(handoffPath, 'utf8'));
  await rename(handoffPath, path.join(outputDirectory, GENERATED_HANDOFF_MODULE));
  await writeFile(handoffPath, overrideSource, { flag: 'wx' });
};

export interface LoopbackBunAdapterOptions {
  readonly out: string;
  readonly precompress: boolean;
}

export const loopbackBunAdapter = (options: LoopbackBunAdapterOptions): Adapter => {
  const adapter = bunAdapter({ out: options.out, precompress: options.precompress });
  return {
    ...adapter,
    adapt: async (builder) => {
      await adapter.adapt(builder);
      await bindRuntimeOrigin(options.out);
    },
  };
};
